/**
 * Stage 9 (B5): applies the native-language reviewer's corrections.
 *
 *   node tooling/i18n/import-translations.mjs <reviewed.csv> [--dry-run]
 *
 * Reads the CSV produced by export-translations.mjs after review. For every row with review_status APPROVED or CORRECTED:
 *   - the key must exist; CORRECTED needs `ar_reviewed`; the reviewer must be named;
 *   - the reviewed Arabic must keep exactly the English placeholders ({name}, {count}, ...) and contain Arabic script;
 * then it regenerates packages/localization/src/dictionaries.ar-reviewed.ts (corrections + per-key review status).
 * Any invalid row stops the import (nothing is written) and is reported. Rebuild and run the localization tests afterwards.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const file = process.argv[2];
const dry = process.argv.includes('--dry-run');
if (!file) throw new Error('Usage: node tooling/i18n/import-translations.mjs <reviewed.csv> [--dry-run]');
const { en, arReviewStatus } = await import(pathToFileURL(join(root, 'packages', 'localization', 'dist', 'index.mjs')).href);

/** Minimal RFC 4180 CSV parser (quoted fields, doubled quotes, CRLF / LF). */
function parse(text) {
  const rows = [];
  let row = [];
  let field = '';
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') q = false;
      else field += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else field += ch;
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((c) => c.trim()));
}

const rows = parse(readFileSync(file, 'utf8').replace(/^﻿/, ''));
const head = rows.shift();
const col = (name) => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error(`Column ${name} is missing`);
  return i;
};
const [cKey, cAr, cCurrent, cReviewer, cStatus] = ['key', 'ar_reviewed', 'arabic_current', 'reviewer', 'review_status'].map(col);
const vars = (s) => [...String(s).matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(' ');
const ARABIC = /[؀-ۿ]/;

const errors = [];
const corrections = {};
const status = { ...(arReviewStatus ?? {}) };
const now = new Date().toISOString().slice(0, 10);
for (const [i, r] of rows.entries()) {
  const key = r[cKey];
  const st = (r[cStatus] ?? '').trim().toUpperCase();
  if (!st) continue;
  const line = i + 2;
  if (!(key in en)) {
    errors.push(`line ${line}: unknown key ${key}`);
    continue;
  }
  if (st !== 'APPROVED' && st !== 'CORRECTED') {
    errors.push(`line ${line}: review_status must be APPROVED or CORRECTED`);
    continue;
  }
  const reviewer = (r[cReviewer] ?? '').trim();
  if (!reviewer) errors.push(`line ${line}: reviewer is required`);
  const text = st === 'CORRECTED' ? (r[cAr] ?? '').trim() : (r[cCurrent] ?? '').trim();
  if (!text) errors.push(`line ${line}: ar_reviewed is required for CORRECTED`);
  if (text && !ARABIC.test(text)) errors.push(`line ${line}: the Arabic text has no Arabic script`);
  if (text && vars(text) !== vars(en[key])) errors.push(`line ${line}: placeholders differ from English (${vars(en[key]) || 'none'})`);
  if (st === 'CORRECTED') corrections[key] = text;
  status[key] = { status: st === 'CORRECTED' ? 'NATIVE_CORRECTED' : 'NATIVE_APPROVED', reviewer, reviewedAt: now };
}
if (errors.length) {
  console.error(`Import refused (${errors.length} problem(s)); nothing was written:\n${errors.slice(0, 50).join('\n')}`);
  process.exit(1);
}
const target = join(root, 'packages', 'localization', 'src', 'dictionaries.ar-reviewed.ts');
const src = readFileSync(target, 'utf8');
const existing = Object.fromEntries([...src.matchAll(/^ {2}'([^']+)': ('(?:[^'\\]|\\.)*'),$/gm)].map((m) => [m[1], m[2]]));
const lit = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const merged = { ...existing, ...Object.fromEntries(Object.entries(corrections).map(([k, v]) => [k, lit(v)])) };
const body = `/**
 * Stage 9 (B5): Arabic corrections from the native-language review. GENERATED by \`tooling/i18n/import-translations.mjs\` from the
 * reviewer's CSV (never edited by hand). Each entry replaces the working Arabic of an existing key; placeholders are checked on import.
 * Empty until the native review has happened: no Arabic string is marked as natively approved before that.
 */
export const arReviewed: Record<string, string> = {
${Object.entries(merged).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  '${k}': ${v},`).join('\n')}
};

/** Review status per key written by the import (NATIVE_APPROVED / NATIVE_CORRECTED). Keys not listed are NEEDS_NATIVE_REVIEW. */
export const arReviewStatus: Record<string, { status: 'NATIVE_APPROVED' | 'NATIVE_CORRECTED'; reviewer: string; reviewedAt: string }> = ${JSON.stringify(status, null, 2)};
`;
console.log(`${Object.keys(corrections).length} correction(s), ${Object.keys(status).length} key(s) with a native review status${dry ? ' (dry run: nothing written)' : ''}`);
if (!dry) writeFileSync(target, body, 'utf8');
